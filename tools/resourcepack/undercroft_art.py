def shaded_rect(c, x0, y0, x1, y1, hi, mid, lo):
    """Box lit from the top: top row hi, bottom row lo."""
    for y in range(y0, y1 + 1):
        col = hi if y == y0 else (lo if y == y1 else mid)
        for x in range(x0, x1 + 1):
            c.set(x, y, col)


def grip(c, x, y0, y1, slant, hi, mid, lo, width=4):
    """Pistol grip going down and back (slant px per 3 rows)."""
    for i, y in enumerate(range(y0, y1 + 1)):
        off = (i * slant) // 3
        for k in range(width):
            col = hi if k == 0 else (lo if k == width - 1 else mid)
            c.set(x - off + k, y, col)


def rivet_pistol(g):
    c = g.Canvas(32, 32, seed=900)
    shaded_rect(c, 13, 12, 25, 14, g.STEEL_L, g.STEEL, g.GUN)        # barrel / slide nose
    shaded_rect(c, 9, 11, 22, 16, g.BRASS_L, g.BRASS, g.BRASS_D)     # receiver (brass nail-gun body)
    for x in range(11, 21, 3):
        c.set(x, 13, g.BRASS_D)                                      # rivet heads
    c.set(25, 13, g.OIL)                                             # muzzle
    shaded_rect(c, 22, 15, 24, 16, g.GUN_L, g.GUN, g.GUN_D)          # rail under the barrel
    grip(c, 10, 17, 25, 2, g.RUST_L, g.RUST, g.RUST_D)
    for x in range(13, 16):
        c.set(x, 19, g.GUN)                                          # trigger guard
    c.set(15, 18, g.GUN); c.set(13, 17, g.STEEL_L)                   # trigger
    c.set(20, 11, g.HAZ); c.set(21, 11, g.HAZ_D)                     # hazard stripe
    c.outline(g.OIL)
    return c


def scrap_smg(g):
    c = g.Canvas(32, 32, seed=901)
    shaded_rect(c, 21, 12, 28, 13, g.STEEL_L, g.STEEL, g.GUN)        # barrel
    for x in range(21, 27, 2):
        c.set(x, 11, g.GUN_D)                                        # barrel shroud holes
        c.set(x + 1, 11, g.GUN)
    shaded_rect(c, 9, 10, 21, 15, g.GUN_L, g.GUN, g.GUN_D)           # receiver
    c.rect(12, 12, 17, 12, g.SOOT)                                   # ejection port
    shaded_rect(c, 16, 16, 18, 25, g.STEEL, g.GUN_L, g.GUN_D)        # long magazine
    for y in range(18, 25, 2):
        c.set(17, y, g.GUN)
    grip(c, 11, 16, 23, 2, g.SOOT, (40, 38, 38), g.OIL)
    c.set(13, 17, g.STEEL_L)
    c.rect(2, 11, 8, 11, g.STEEL)                                    # wire stock
    c.rect(2, 15, 8, 15, g.STEEL)
    c.rect(2, 11, 2, 15, g.STEEL_L)
    c.set(28, 13, g.OIL)
    c.set(19, 10, g.RED); c.set(20, 10, g.RED_D)                     # scrap paint
    c.outline(g.OIL)
    return c


def breach_shotgun(g):
    c = g.Canvas(32, 32, seed=902)
    shaded_rect(c, 14, 11, 30, 12, g.STEEL_L, g.STEEL, g.GUN)        # barrel
    shaded_rect(c, 15, 13, 28, 14, g.GUN_L, g.GUN, g.GUN_D)          # tube magazine
    shaded_rect(c, 18, 14, 24, 16, g.RUST_L, g.RUST, g.RUST_D)       # pump
    for x in range(19, 24, 2):
        c.set(x, 15, g.RUST_D)
    shaded_rect(c, 8, 10, 15, 15, g.GUN_L, g.GUN, g.GUN_D)           # receiver
    c.set(10, 12, g.HAZ); c.set(11, 12, g.HAZ); c.set(12, 12, g.HAZ_D)
    for i, x in enumerate(range(1, 9)):                              # stock, tapering
        top = 11 + max(0, (8 - i) // 4) - (1 if i > 5 else 0)
        for y in range(top, 17 - (i < 2)):
            c.set(x, y, g.RUST_L if y == top else (g.RUST_D if y >= 15 else g.RUST))
    grip(c, 10, 16, 20, 2, g.RUST, g.RUST_D, g.SOOT, width=3)
    c.set(12, 17, g.STEEL_L)
    c.set(30, 11, g.OIL); c.set(30, 12, g.OIL)
    c.outline(g.OIL)
    return c


def bolt_rifle(g):
    c = g.Canvas(32, 32, seed=903)
    shaded_rect(c, 17, 13, 31, 14, g.STEEL_L, g.STEEL, g.GUN)        # long barrel
    c.rect(29, 12, 31, 12, g.GUN_D)                                  # muzzle brake
    c.rect(29, 15, 31, 15, g.GUN_D)
    shaded_rect(c, 8, 12, 18, 16, g.OLIVE_L, g.OLIVE, g.OLIVE_D)     # receiver
    shaded_rect(c, 9, 8, 19, 10, g.GUN_L, g.GUN, g.SOOT)             # scope
    c.set(19, 9, g.CYAN); c.set(9, 9, g.CYAN_D)                      # lenses
    c.rect(11, 11, 11, 11, g.GUN); c.rect(17, 11, 17, 11, g.GUN)     # scope mounts
    c.set(14, 17, g.STEEL_L); c.set(15, 18, g.STEEL_L)               # bolt handle
    for i, x in enumerate(range(0, 9)):                              # stock
        for y in range(12 + (1 if i < 3 else 0), 18 - (1 if i > 6 else 0)):
            c.set(x, y, g.OLIVE_L if y == 12 + (1 if i < 3 else 0) else (g.OLIVE_D if y >= 16 else g.OLIVE))
    grip(c, 9, 17, 21, 2, g.OLIVE, g.OLIVE_D, g.SOOT, width=3)
    c.set(31, 13, g.OIL); c.set(31, 14, g.OIL)
    c.outline(g.OIL)
    return c


def plasma_lance(g, frame=0):
    import math
    c = g.Canvas(32, 32, seed=904)
    shaded_rect(c, 6, 11, 22, 17, g.WHITE, g.STEEL_L, g.STEEL)       # body
    shaded_rect(c, 22, 12, 27, 16, g.GUN_L, g.GUN, g.GUN_D)          # emitter housing
    for x in range(23, 27):                                          # emitter fins
        if x % 2:
            c.set(x, 11, g.GUN); c.set(x, 17, g.GUN)
    for x in range(8, 21):                                           # glowing coil channel
        t = (math.sin((x + frame * 2) * 0.9) + 1) / 2
        c.set(x, 14, g.mix(g.CYAN_D, g.CYAN_L, t))
    c.rect(27, 13, 29, 15, g.CYAN)                                   # muzzle glow
    c.set(30, 14, g.CYAN_L)
    c.set(29, 14, g.WHITE)
    shaded_rect(c, 14, 18, 17, 20, g.CYAN_D, g.CYAN_D, g.GUN_D)      # cell
    grip(c, 9, 18, 24, 2, g.GUN_L, g.GUN, g.GUN_D)
    c.rect(2, 13, 6, 15, g.STEEL)                                    # short stock
    c.set(2, 13, g.STEEL_L)
    c.outline(g.OIL)
    return c


def guns(g):
    out = g.SP / "textures" / "item" / "gun"
    for name, fn in (("rivet_pistol", rivet_pistol), ("scrap_smg", scrap_smg), ("breach_shotgun", breach_shotgun),
                     ("bolt_rifle", bolt_rifle)):
        fn(g).save(out / f"{name}.png")
        gun_model(g, f"gun/{name}")
    g.stack([plasma_lance(g, f) for f in range(6)]).save(out / "plasma_lance.png")
    g.animate(out / "plasma_lance.png", 2)
    gun_model(g, "gun/plasma_lance")


