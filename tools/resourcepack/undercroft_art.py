def draw(g, sprite, pal):
    d, m, l, h, a, A = pal
    colors = {"d": d, "m": m, "l": l, "h": h, "a": a, "A": A, "k": g.OIL, "w": g.WHITE}
    c = g.Canvas()
    rows = SPRITES[sprite].strip("\n").split("\n")
    for y, row in enumerate(rows[:16]):
        for x, ch in enumerate(row[:16]):
            if ch in colors:
                c.set(x, y, colors[ch])
    c.outline(g.OIL)
    return c


