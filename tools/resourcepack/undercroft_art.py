def gun_model(g, key):
    g.write_json(g.SP / "models" / "item" / f"{key}.json", {
        "parent": "minecraft:item/generated",
        "textures": {"layer0": f"spacepunk:item/{key}"},
        "display": GUN_DISPLAY,
    })
    g.item_definition(key)


