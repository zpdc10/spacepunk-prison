def draw(g, sprite: str, pal):
    d, m, l, h, a, A = pal
    colors = {"d": d, "m": m, "l": l, "h": h, "a": a, "A": A, "k": g.OIL, "w": g.WHITE}
    c = g.Canvas()
    rows = [r for r in SPRITES[sprite].strip("\n").split("\n")]
    oy = max(0, (16 - len(rows)) // 2)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row[:16]):
            if ch in colors:
                c.set(x, y + oy, colors[ch])
    c.outline(g.OIL)
    return c


def raredrops(g):
    out = g.SP / "textures" / "item" / "raredrop"
    for drop_id, (sprite, pal) in palettes(g).items():
        draw(g, sprite, pal).save(out / f"{drop_id}.png")
        g.generated_model(f"raredrop/{drop_id}")
